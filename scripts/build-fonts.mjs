// Rebuilds assets/fonts, css/fonts.css and the font block of sw.js from @fontsource-variable packages.
//   npm pack @fontsource-variable/<name> for each font, extract each tarball into its own folder under <dir>, then:
//   node scripts/build-fonts.mjs <dir>
// Fonts are SIL OFL 1.1. Subsets are the ones a CV realistically needs: Latin, Latin-ext, Cyrillic, Greek, Vietnamese.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync, rmSync } from "node:fs";
import { join } from "node:path";

const FONTS = [
  ["inter", "Inter"],
  ["dm-sans", "DM Sans"],
  ["space-grotesk", "Space Grotesk"],
  ["lora", "Lora"],
  ["playfair-display", "Playfair Display"],
  ["source-serif-4", "Source Serif 4"],
  ["jetbrains-mono", "JetBrains Mono"],
];
const SUBSETS = ["latin", "latin-ext", "cyrillic", "greek", "vietnamese"];
const root = new URL("..", import.meta.url).pathname;
const src = process.argv[2];
if (!src) throw new Error("usage: node scripts/build-fonts.mjs <extracted-packages-dir>");

const pkgDirs = readdirSync(src).map((d) => join(src, d, "package")).filter(existsSync);
let css = `/* Self-hosted, open-licence (SIL OFL 1.1) variable fonts. See assets/fonts/*/LICENSE.txt.
 * Generated by scripts/build-fonts.mjs. Upright and italic files, Latin, Latin-ext, Cyrillic, Greek and Vietnamese.
 * Browsers fetch only the subsets a document actually uses. Other scripts fall back to system fonts. */
`;
const precache = [];

for (const [slug, family] of FONTS) {
  const pkg = pkgDirs.find((d) => existsSync(join(d, "files", `${slug}-latin-wght-normal.woff2`)));
  if (!pkg) throw new Error(`package for ${slug} not found in ${src}`);
  const out = join(root, "assets/fonts", slug);
  mkdirSync(out, { recursive: true });
  for (const f of readdirSync(out)) if (f.endsWith(".woff2")) rmSync(join(out, f));
  copyFileSync(join(pkg, "LICENSE"), join(out, "LICENSE.txt"));
  for (const style of ["normal", "italic"]) {
    const sheet = join(pkg, style === "normal" ? "wght.css" : "wght-italic.css");
    if (!existsSync(sheet)) continue; // e.g. Space Grotesk and DM Sans italic differ per package
    const blocks = readFileSync(sheet, "utf8").match(/@font-face\s*{[^}]*}/g) || [];
    for (const block of blocks) {
      const file = /files\/([^)]+\.woff2)/.exec(block)?.[1];
      const subset = file && SUBSETS.find((s) => file === `${slug}-${s}-wght-${style}.woff2`);
      if (!subset) continue;
      copyFileSync(join(pkg, "files", file), join(out, file));
      precache.push(`assets/fonts/${slug}/${file}`);
      const weight = /font-weight:\s*([^;]+);/.exec(block)[1];
      const range = /unicode-range:\s*([^;]+);/.exec(block)[1].replace(/,/g, ", ");
      css += `
/* ${slug} ${subset} ${style} */
@font-face {
  font-family: "${family} Variable";
  font-style: ${style};
  font-display: swap;
  font-weight: ${weight};
  src: url("../assets/fonts/${slug}/${file}") format("woff2-variations");
  unicode-range: ${range};
}
`;
    }
  }
}
writeFileSync(join(root, "css/fonts.css"), css);

const swPath = join(root, "sw.js");
let sw = readFileSync(swPath, "utf8");
const lines = precache.map((p) => `  "${p}",`).join("\n");
sw = sw.replace(/(  \/\/ fonts:start\n)[\s\S]*?(  \/\/ fonts:end\n)/, `$1${lines}\n$2`);
if (!sw.includes("// fonts:start")) throw new Error("sw.js is missing the // fonts:start / // fonts:end markers");
writeFileSync(swPath, sw);
console.log(`${precache.length} font files, css/fonts.css and sw.js written`);
