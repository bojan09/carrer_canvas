// Renders assets/sample/avatar.svg to a 320px JPEG and writes it as a data URL module.
// The avatar is an original illustration owned by this project (no stock photography).
// Usage: node scripts/generate-sample-photo.mjs   (needs Playwright + Chromium)
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
const { chromium } = createRequire(import.meta.url)("playwright");

const svg = await readFile(new URL("../assets/sample/avatar.svg", import.meta.url), "utf8");
const browser = await chromium.launch();
const page = await browser.newPage();
const url = await page.evaluate(async (markup) => {
  const img = new Image();
  img.src = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(markup)}`;
  await img.decode();
  const c = document.createElement("canvas");
  c.width = c.height = 320;
  c.getContext("2d").drawImage(img, 0, 0, 320, 320);
  return c.toDataURL("image/jpeg", 0.86);
}, svg);
await browser.close();
const out = `/* Generated by scripts/generate-sample-photo.mjs from assets/sample/avatar.svg. Do not edit by hand.
 * An original illustrated avatar used only in fictional sample resumes. */
export const SAMPLE_PHOTO = Object.freeze({ data: "${url}", width: 320, height: 320 });
`;
await writeFile(new URL("../js/models/sample-photo.js", import.meta.url), out);
console.log(`sample photo: ${url.length} chars`);
